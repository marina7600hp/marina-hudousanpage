/* ===================================================================
 * bukken-portals.js  ―  サイトごとの「転記手順」
 *
 * 【2026-09 各社に確認した結果】
 *   スーモ・スマイミー・きまるーむとも、CSVでの一括入稿には対応していない
 *   との回答でした。したがって各サイトへの登録は管理画面への手入力になります。
 *
 *   このファイルは、その手入力を少しでも速くするためのものです。
 *   物件の入力自体は bukken.html で1回だけ行い、ここで定義した順番に
 *   「コピー」ボタンが並んだ転記画面が作られます。
 *
 * -------------------------------------------------------------------
 * 【steps の書き方】
 *
 *   実際にサイトの登録画面を開いて、上から出てくる順に並べてください。
 *   そのとおりの順番でコピーボタンが並ぶので、画面を行ったり来たりせず
 *   上から順に貼り付けていけます。
 *
 *   steps: [
 *     { section: '基本情報' },                        ← 見出し（任意）
 *     { label: '建物名', from: 'buildingName' },      ← サイト側の名称 : こちらの項目
 *     { label: '住所',   from: function (v) {         ← 複数項目をつなげる場合
 *         return v.pref + v.city + v.town + v.banchi;
 *       } },
 *     { label: '最寄駅', from: 'sta1', note: '「駅」は付けない' },  ← 注意書き（任意）
 *   ]
 *
 *   label … そのサイトの画面に表示されている項目名を書いてください
 *   from  … bukken-schema.js の key（日本語ラベル付きの一覧があります）
 *   note  … 「全角で入れる」「単位は不要」など、間違えやすい点のメモ
 *
 *   steps を空 [] のままにしておくと、bukken-schema.js の並び順で
 *   全項目が表示されます（今はこの状態です）。
 *   サイトの画面順に並べ替えると、さらに速くなります。
 * =================================================================== */

